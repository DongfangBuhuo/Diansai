/************************************************************************
 * @file app_ir.h
 * @brief APP 层红外模块头文件
 *
 * 详细描述:
 * - 功能1: 声明红外模块初始化接口
 * - 功能2: 声明红外模块任务创建接口
 * - 功能3: 为后续红外采集、滤波和状态解析扩展预留入口
 *
 * @author DFBH
 * @date 2026-06-18
 * @version 1.0.0
 *
 * @note 本模块位于 APP 层, 通过 BSP IR 驱动访问底层红外设备
 * @warning 在创建红外任务前, 应先完成 AppIr_Init 初始化
 ************************************************************************/
#ifndef __APP_IR_H
#define __APP_IR_H

/**
 * @brief APP 层红外模块初始化
 *
 * 功能说明:
 * - 获取默认红外设备对象
 * - 调用 BSP 层接口完成红外驱动初始化
 *
 * @retval None
 */
void AppIr_Init(void);

/**
 * @brief APP 层红外任务创建接口
 *
 * 功能说明:
 * - 创建红外采集任务
 * - 将默认红外设备对象作为任务参数传入
 *
 * @retval None
 */
void AppIr_TaskCreate(void);

#endif /* __APP_IR_H */
